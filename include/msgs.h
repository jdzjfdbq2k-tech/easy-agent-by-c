#ifndef MSGS_H
#define MSGS_H

/*
 * msgs —— 对话历史。
 *
 * 这是 agent 里唯一"有状态"的东西。除了它，其它模块都是纯函数式的：
 * 给同样的输入就得到同样的输出。所以这个模块写对了，agent 就稳了一半。
 *
 * ---------------------------------------------------------------------
 * 为什么用不透明类型（opaque type）
 * ---------------------------------------------------------------------
 * 下面只声明 `typedef struct msgs msgs;`，不写出结构体成员。
 * 调用方拿到的永远是一个指针，看不到里面是什么，也无法直接改字段。
 *
 * 好处是：内部到底用 cJSON 数组、还是 char* 数组、还是别的，全都可以换，
 * 而外面这四个函数的签名一行都不用改。llm.h / main.c 都不会被牵连。
 *
 * 如果你以后想拆掉 cJSON，只需要重写 msgs.c，其它文件一个字不用动。
 * 这就是"接口与实现分离"在 C 里最朴素的用法。
 *
 * ---------------------------------------------------------------------
 * 为什么不直接在 main.c 里拼字符串
 * ---------------------------------------------------------------------
 * 因为 JSON 转义。
 *
 * 工具读回来的文件内容里会有双引号、反斜杠、换行符。手工拼字符串的话，
 * 一个 `"` 就能把整个请求体拼坏，接口返回的错误信息通常指向别的地方，
 * 你会查很久。所以下面 msgs_add_tool_result() 内部必须用 cJSON 来构造
 * 那一条消息，让 cJSON 负责转义，而不是靠 strbuf 往上糊。
 *
 * ---------------------------------------------------------------------
 * 内存所有权
 * ---------------------------------------------------------------------
 * msgs 对象本身：msgs_new() 创建，msgs_free() 释放。
 * 传进去的字符串：msgs 内部会复制一份，调用方传完就可以 free。
 * 拿出来的字符串：msgs_to_json() 的返回值由调用方 free。
 */

typedef struct msgs msgs;

/* 新建一个空的对话。失败返回 NULL。 */
msgs *msgs_new(void);

/* 释放对话及其内部所有消息。可以安全地传 NULL。 */
void msgs_free(msgs *m);

/*
 * 追加一条用户消息：{"role":"user","content":"<text>"}
 * 每一轮的最开始调用它，把用户这一轮的要求写进去。
 * 内容会被 JSON 转义，随便传什么字符都安全。
 */
void msgs_add_user(msgs *m, const char *text);

/*
 * 追加一条助手消息，内容是**原样一段 JSON**。
 *
 * 参数 message_json 应该直接来自 llm_result.assistant_json ——
 * 也就是模型返回的 choices[0].message 那个对象的原始文本。
 *
 * 为什么要"原样照抄"而不是自己重新拼一条：
 *   带 tool_calls 的助手消息里，除了 tool_calls 还有可能有别的字段，
 *   而且各家服务商对哪些字段必须保留、哪些必须丢掉的要求不完全一样。
 *   原样回填是保真度最高的做法：模型发来什么，就还回去什么。
 *   （如果某个服务商报错说某字段不该出现，那问题一定在这里。）
 *
 * 调用方仍然保留传入字符串的所有权，函数内部会复制。
 */
void msgs_add_assistant_raw(msgs *m, const char *message_json);

/*
 * 追加一条工具执行结果：{"role":"tool","tool_call_id":"...","content":"..."}
 *
 *   tool_call_id  必须原样来自 tool_call.id，不能自己编号。
 *                 模型靠它把结果对应回自己发出的那个请求，对不上会报错。
 *   output        tool_run() 的返回值，里面可能包含文件内容、引号、换行，
 *                 这里必须走 cJSON 构造来保证转义正确。
 */
void msgs_add_tool_result(msgs *m, const char *tool_call_id, const char *output);

/*
 * 把整个历史序列化成一个 JSON **数组文本**，形如：
 *   [{"role":"user","content":"..."},{"role":"assistant","tool_calls":[...]}]
 *
 * 返回值由调用方 free。空历史返回 "[]"，不会返回 NULL。
 *
 * 这个函数可以安全地传 NULL（会返回 "[]"），这样调用方少写一个判空分支 ——
 * 但正常流程里你应该在建好对话之后才调它。
 */
char *msgs_to_json(const msgs *m);

/* 当前有多少条消息。主要给调试和断言用。 */
int msgs_count(const msgs *m);

#endif
